export function hasNonZeroCombiningClass(char: string): boolean {
  if (!char) return false;
  const cp = char.codePointAt(0)!;
  let lo = 0;
  let hi = NON_ZERO_COMBINING_RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [start, end] = NON_ZERO_COMBINING_RANGES[mid]!;
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return true;
  }
  return false;
}
